def convert_text(text: str) -> str:
    """转换文本中的繁体为简体（仅针对映射表中的字符）"""
    result = []
    for char in text:
        result.append(TRADITIONAL_TO_SIMPLIFIED.get(char, char))
    return ''.join(result)


def convert_file(input_path: Path, output_path: Path = None) -> Path:
    """转换文件内容"""
    with open(input_path, "r", encoding="utf-8") as f:
        content = f.read()
    
    converted = convert_text(content)
    
    if not output_path:
        output_path = input_path.parent / f"{input_path.stem}_简体{input_path.suffix}"
    
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(converted)
    
    print(f"✅ 转换完成！输出：{output_path}")
    return output_path


